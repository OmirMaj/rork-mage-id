/**
 * INSPECTION-RESULT VERTICAL — the backward half of the permit-roadmap
 * automation (utils/automation/inspectionResultToScheduleWork.ts).
 *
 * The forward vertical (roadmapToScheduleWork → eventToScheduleWork) BOOKS an
 * inspection ahead of the task it gates via an FS+lag dependency. This vertical
 * reacts when the contractor marks that inspection PASSED or FAILED. We assert
 * on the PURE adapter, exercised through the SAME real engine the screen wires
 * up (getSuccessors / recalculateStartDays / eventToScheduleWork) — never a
 * re-implementation:
 *
 *   (a) PASS releases exactly the gated successor(s) — the inspection→successor
 *       link is dropped so it can start — and nothing else.
 *   (b) FAIL keeps the gated successors BLOCKED, produces exactly one
 *       re-inspection DRAFT (honest 'dob_inspection' library provenance,
 *       sourceEventRef '<inspId>:reinspect', isAutoGenerated) AND exactly one
 *       hazard DRAFT (sourceInspectionId = inspection id).
 *   (c) IDEMPOTENT re-run: re-marking PASSED releases the same set; re-marking
 *       FAILED does not duplicate the re-inspection task or the hazard.
 *   (d) NOTHING mutates without the commit call — the adapter is a pure function
 *       of its inputs; the input schedule object is never touched.
 *
 * The fixture's inspection→gating linkage is built by RUNNING THE REAL FORWARD
 * VERTICAL (roadmapToScheduleWork + mergeReviewLines), so the two halves move in
 * lockstep — if the forward vertical changes how it links, this test sees it.
 */

import {
  inspectionResultToScheduleWork,
  reinspectRefId,
} from '@/utils/automation/inspectionResultToScheduleWork';
import {
  roadmapToScheduleWork,
  mergeReviewLines,
  ROADMAP_FEATURE,
} from '@/utils/automation/roadmapToScheduleWork';
import { getSuccessors, getDepLinks } from '@/utils/scheduleEngine';
import type { ProjectSchedule, RoadmapInspection, ScheduleTask } from '@/types';

// ── Fixture ──────────────────────────────────────────────────────────────────
// A gating task ("Foundation pour") the inspection precedes, plus a downstream
// task ("Framing") that depends on the gating task. The inspection is booked
// ahead of the pour by the forward vertical.
const GATING_ID = 'task-foundation-pour';
const DOWNSTREAM_ID = 'task-framing';
const INSP_ID = 'insp-foundation';

function baseTask(over: Partial<ScheduleTask> & { id: string; title: string }): ScheduleTask {
  return {
    phase: 'General',
    durationDays: 3,
    startDay: 1,
    progress: 0,
    crew: 'gc',
    dependencies: [],
    notes: '',
    status: 'not_started',
    ...over,
  };
}

function inspection(): RoadmapInspection {
  return {
    id: INSP_ID,
    type: 'foundation',
    title: 'Foundation / pre-pour inspection',
    description: 'Rebar + forms before concrete.',
    gatesTaskHint: 'Foundation pour',
    gatesTaskId: GATING_ID,
    leadTimeDays: 2,
    status: 'scheduled',
  };
}

/** A raw (pre-inspection) schedule: pour, then framing after pour. */
function rawSchedule(): ProjectSchedule {
  return {
    id: 'sched-1',
    projectId: 'proj-1',
    name: 'Schedule',
    startDate: '2026-09-01',
    tasks: [
      baseTask({ id: GATING_ID, title: 'Foundation pour', phase: 'Foundation' }),
      baseTask({
        id: DOWNSTREAM_ID,
        title: 'Framing',
        phase: 'Framing',
        dependencies: [GATING_ID],
        dependencyLinks: [{ taskId: GATING_ID, type: 'FS', lagDays: 0 }],
      }),
    ],
  } as ProjectSchedule;
}

/** Run the REAL forward vertical to book the inspection ahead of the pour —
 *  this is exactly what a committed inspection schedule looks like. */
function scheduledFixture(): ProjectSchedule {
  const raw = rawSchedule();
  const lines = roadmapToScheduleWork([inspection()], raw);
  const merged = mergeReviewLines(lines, raw.tasks ?? []);
  return { ...raw, tasks: merged };
}

const OPTS = {
  projectId: 'proj-1',
  createdBy: 'user-1',
  now: '2026-09-05T12:00:00.000Z',
  hazardId: 'hazard-1',
};

// The committed inspection task the forward vertical stamped.
function inspectionTaskId(schedule: ProjectSchedule): string {
  const t = (schedule.tasks ?? []).find(
    (x) => x.sourceEventRef?.feature === ROADMAP_FEATURE && x.sourceEventRef?.id === INSP_ID,
  );
  return t!.id;
}

describe('inspectionResultToScheduleWork — fixture sanity', () => {
  it('the forward vertical actually gated the pour on the inspection', () => {
    const sched = scheduledFixture();
    const inspTaskId = inspectionTaskId(sched);
    const successors = getSuccessors(inspTaskId, sched.tasks ?? []);
    // The pour depends on the inspection (that is what "release" undoes).
    expect(successors.map((t) => t.id)).toContain(GATING_ID);
  });
});

describe('(a) PASS releases exactly the gated successor(s), nothing else', () => {
  it('drops the inspection→successor link on the gated task and no other', () => {
    const sched = scheduledFixture();
    const inspTaskId = inspectionTaskId(sched);
    const gatedIds = getSuccessors(inspTaskId, sched.tasks ?? []).map((t) => t.id);

    const work = inspectionResultToScheduleWork(inspection(), sched, 'passed', OPTS);

    expect(work.result).toBe('passed');
    // Released set == exactly the tasks the inspection gated.
    expect(new Set(work.releasedTaskIds)).toEqual(new Set(gatedIds));
    expect(work.tasks).toBeDefined();

    // Each released task no longer depends on the inspection task; every other
    // dependency it had is preserved.
    for (const id of gatedIds) {
      const before = (sched.tasks ?? []).find((t) => t.id === id)!;
      const after = work.tasks!.find((t) => t.id === id)!;
      const beforeDeps = getDepLinks(before).map((l) => l.taskId);
      const afterDeps = getDepLinks(after).map((l) => l.taskId);
      expect(afterDeps).not.toContain(inspTaskId);
      // Preserved: every non-inspection predecessor survives.
      for (const d of beforeDeps.filter((x) => x !== inspTaskId)) {
        expect(afterDeps).toContain(d);
      }
    }

    // Non-gated tasks (e.g. the pure downstream framing task) are untouched in
    // their dependency structure.
    const framingBefore = (sched.tasks ?? []).find((t) => t.id === DOWNSTREAM_ID)!;
    const framingAfter = work.tasks!.find((t) => t.id === DOWNSTREAM_ID)!;
    expect(getDepLinks(framingAfter).map((l) => l.taskId)).toEqual(
      getDepLinks(framingBefore).map((l) => l.taskId),
    );

    // PASS produces NO re-inspection and NO hazard.
    expect(work.reinspectionDraft).toBeUndefined();
    expect(work.hazardDraft).toBeUndefined();
  });

  it('PASS with no committed inspection task releases nothing', () => {
    const raw = rawSchedule(); // never ran forward vertical → no inspection task
    const work = inspectionResultToScheduleWork(inspection(), raw, 'passed', OPTS);
    expect(work.result).toBe('passed');
    expect(work.releasedTaskIds).toEqual([]);
    expect(work.tasks).toBeUndefined();
  });
});

describe('(b) FAIL keeps successors blocked + one re-inspection draft + one hazard draft', () => {
  it('produces the blocked set, an honest re-inspection draft, and a hazard draft', () => {
    const sched = scheduledFixture();
    const inspTaskId = inspectionTaskId(sched);
    const gatedIds = getSuccessors(inspTaskId, sched.tasks ?? []).map((t) => t.id);

    const work = inspectionResultToScheduleWork(inspection(), sched, 'failed', OPTS);

    expect(work.result).toBe('failed');

    // Successors stay BLOCKED — same set, and each STILL depends on the failed
    // inspection task in the committed task list.
    expect(new Set(work.blockedTaskIds)).toEqual(new Set(gatedIds));
    for (const id of gatedIds) {
      const after = work.tasks!.find((t) => t.id === id)!;
      expect(getDepLinks(after).map((l) => l.taskId)).toContain(inspTaskId);
    }

    // Exactly ONE re-inspection draft, honest provenance, stamped ref.
    const draft = work.reinspectionDraft!;
    expect(draft).toBeDefined();
    expect(draft.isAutoGenerated).toBe(true);
    expect(draft.sourceEventRef).toEqual({
      feature: ROADMAP_FEATURE,
      id: reinspectRefId(INSP_ID),
    });
    // Honest lead provenance — library default for a DOB inspection, NOT
    // jurisdiction/high by fiat.
    expect(work.reinspectionLead!.source).toBe('default');
    expect(work.reinspectionLead!.days).toBeGreaterThan(0);

    // The re-inspection draft is actually present in the committed task list,
    // exactly once.
    const draftsInTasks = work.tasks!.filter(
      (t) => t.sourceEventRef?.id === reinspectRefId(INSP_ID),
    );
    expect(draftsInTasks).toHaveLength(1);

    // Exactly ONE hazard draft, carrying the inspection id as its source.
    const hz = work.hazardDraft!;
    expect(hz).toBeDefined();
    expect(hz.sourceInspectionId).toBe(INSP_ID);
    expect(hz.status).toBe('open');
    expect(hz.projectId).toBe('proj-1');
    expect(hz.id).toBe('hazard-1');
  });
});

describe('(c) idempotent re-run', () => {
  it('re-marking PASSED releases the same set (no further change)', () => {
    const sched = scheduledFixture();
    const first = inspectionResultToScheduleWork(inspection(), sched, 'passed', OPTS);
    // Feed the committed result back in and re-mark passed.
    const committed = { ...sched, tasks: first.tasks! };
    const second = inspectionResultToScheduleWork(inspection(), committed, 'passed', OPTS);
    // The inspection task no longer gates anything, so nothing is released again.
    expect(second.releasedTaskIds).toEqual([]);
    // The dependency structure is stable across the re-run.
    const depsFor = (s: ProjectSchedule, id: string) =>
      getDepLinks((s.tasks ?? []).find((t) => t.id === id)!).map((l) => l.taskId).sort();
    for (const id of first.releasedTaskIds ?? []) {
      const afterSecond = second.tasks
        ? second.tasks.find((t) => t.id === id)
        : (committed.tasks ?? []).find((t) => t.id === id);
      expect(getDepLinks(afterSecond!).map((l) => l.taskId).sort()).toEqual(
        depsFor(committed, id),
      );
    }
  });

  it('re-marking FAILED does not duplicate the re-inspection task or the hazard', () => {
    const sched = scheduledFixture();
    const first = inspectionResultToScheduleWork(inspection(), sched, 'failed', OPTS);
    // Commit the first fail's tasks (draft re-inspection now lives in schedule).
    const committed = { ...sched, tasks: first.tasks! };

    const second = inspectionResultToScheduleWork(inspection(), committed, 'failed', OPTS);

    // Only ONE task with the re-inspection ref, even after re-running.
    const reinspectTasks = second.tasks!.filter(
      (t) => t.sourceEventRef?.id === reinspectRefId(INSP_ID),
    );
    expect(reinspectTasks).toHaveLength(1);

    // The committed task count did not grow on the re-run (no duplicate row).
    expect(second.tasks!.length).toBe(committed.tasks!.length);

    // The hazard draft dedups on the same sourceInspectionId (caller keys off
    // it) — same source, not a second distinct source.
    expect(second.hazardDraft!.sourceInspectionId).toBe(
      first.hazardDraft!.sourceInspectionId,
    );
  });
});

describe('(d) nothing mutates without the commit call', () => {
  it('the input schedule + inspection are never mutated by the pure adapter', () => {
    const sched = scheduledFixture();
    const snapshot = JSON.stringify(sched);
    const insp = inspection();
    const inspSnapshot = JSON.stringify(insp);

    inspectionResultToScheduleWork(insp, sched, 'passed', OPTS);
    inspectionResultToScheduleWork(insp, sched, 'failed', OPTS);

    // The adapter returns NEW objects; the caller's schedule/inspection are
    // untouched until it chooses to commit the returned tasks.
    expect(JSON.stringify(sched)).toBe(snapshot);
    expect(JSON.stringify(insp)).toBe(inspSnapshot);
  });
});
